/**
 * Normalizes input slug and returns the grade-specific buttweld fitting image.
 * @param {string} gradeSlug - Grade slug or identifier
 * @returns {string|null} Resolved image asset
 */
export function getButtWeldFittingGradeImage(gradeSlug) {
  if (!gradeSlug) return null;
  const clean = String(gradeSlug).toLowerCase().trim();
  if (BUTT_WELD_FITTING_GRADE_IMAGES[clean]) {
    return BUTT_WELD_FITTING_GRADE_IMAGES[clean];
  }

  // Strip generic suffixes if any
  const stripped = clean.replace(/-(buttweld-fittings|pipe-fittings|fittings)$/, '');
  if (BUTT_WELD_FITTING_GRADE_IMAGES[stripped]) {
    return BUTT_WELD_FITTING_GRADE_IMAGES[stripped];
  }

  // Look through keys with flexible partial matching
  for (const [key, img] of Object.entries(BUTT_WELD_FITTING_GRADE_IMAGES)) {
    if (key.length > 3 && (clean.includes(key) || key.includes(clean))) {
      return img;
    }
  }

  return null;
}

// Re-export alias for convenience across pipe fitting modules
export const getPipeFittingGradeImage = getButtWeldFittingGradeImage;
